const LANGUAGE_NAMES = {
    en: 'English',
    fr: 'Français',
    ar: 'العربية',
    es: 'Español',
    zh: '中文',
    ja: '日本語'
};

const RTL_LANGUAGES = ['ar'];

let currentLang = localStorage.getItem('oops_lang') || 'en';

export function t(key, params = {}) {
    const dict = translations[currentLang] || translations.en;
    let text = dict[key] || translations.en[key] || key;
    for (const [param, value] of Object.entries(params)) {
        text = text.replace(`{${param}}`, value);
    }
    return text;
}

export function getCurrentLang() {
    return currentLang;
}

export function getLanguageNames() {
    return LANGUAGE_NAMES;
}

export function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('oops_lang', lang);

    // Update dir attribute for RTL
    const html = document.documentElement;
    if (RTL_LANGUAGES.includes(lang)) {
        html.setAttribute('dir', 'rtl');
        html.setAttribute('lang', lang);
    } else {
        html.setAttribute('dir', 'ltr');
        html.setAttribute('lang', lang);
    }

    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (key) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t(key);
            } else {
                el.textContent = t(key);
            }
        }
    });

    // Dispatch event for JS modules to update dynamic content
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

export function initI18n() {
    const savedLang = localStorage.getItem('oops_lang') || 'en';
    setLanguage(savedLang);
}
